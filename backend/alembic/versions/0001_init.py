def _enable_rls() -> None:
    """Row level security as defence in depth behind application scoping.

    Policies compare ``tenant_id`` with ``current_setting('arix.tenant_id')``,
    which ``arix.db.session.tenant_session`` sets per transaction.  ARIX-level
    work sets ``arix.bypass_rls`` instead.  FORCE makes the policy apply to the
    table owner too, so only a superuser can read across tenants.
    """
    for table in TENANT_TABLES:
        op.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
        op.execute(f"ALTER TABLE {table} FORCE ROW LEVEL SECURITY")
        op.execute(
            f"""
            CREATE POLICY tenant_isolation ON {table}
            USING (
                coalesce(current_setting('arix.bypass_rls', true), 'off') = 'on'
                OR tenant_id = nullif(current_setting('arix.tenant_id', true), '')::uuid
            )
            WITH CHECK (
                coalesce(current_setting('arix.bypass_rls', true), 'off') = 'on'
                OR tenant_id = nullif(current_setting('arix.tenant_id', true), '')::uuid
            )
            """
        )


